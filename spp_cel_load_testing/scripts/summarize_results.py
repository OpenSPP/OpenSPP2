#!/usr/bin/env python3
# Utility script to summarize CEL benchmark JSON results.
# Intended for quick CLI/CI/AI consumption.
# Standalone CLI tool: report output goes to stdout by design.
# pylint: disable=print-used

import argparse
import json
from collections import Counter, defaultdict
from pathlib import Path


def summarize(path: Path, top_n: int = 15) -> None:
    data = json.loads(path.read_text())

    summary = data.get("summary", {})
    results = data.get("results", [])

    print("OVERALL SUMMARY")
    print("---------------")
    print(
        f"Total tests: {summary.get('total_tests')}  "
        f"Passed: {summary.get('passed')}  "
        f"Failed: {summary.get('failed')}  "
        f"Errors: {summary.get('errors')}  "
        f"Pass rate: {summary.get('pass_rate', 0):.1f}%"
    )
    print(f"Total time (s): {summary.get('total_time', 0.0):.3f}")
    print()

    # Group by suite prefix (before first dot)
    by_suite = defaultdict(list)
    for r in results:
        name = r.get("test_name", "")
        suite = name.split(".", 1)[0] if "." in name else "unknown"
        by_suite[suite].append(r)

    print("SUITE SUMMARY")
    print("-------------")
    for suite, tests in sorted(by_suite.items()):
        total_t = sum(t.get("elapsed_time", 0.0) for t in tests)
        avg_t = total_t / len(tests) if tests else 0.0
        statuses = Counter(t.get("status") for t in tests)
        print(
            f"{suite:11s} : tests={len(tests):2d}  "
            f"total={total_t:7.3f}s  avg={avg_t * 1000:7.2f}ms  "
            f"status={dict(statuses)}"
        )

    print()
    print(f"TOP {top_n} SLOWEST TESTS")
    print("----------------------")
    slow = sorted(results, key=lambda r: r.get("elapsed_time", 0.0), reverse=True)[:top_n]
    for r in slow:
        print(f"{r.get('test_name', ''):<60s} {r.get('elapsed_time', 0.0):7.3f}s  {r.get('status')}")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Summarize CEL benchmark JSON results (generated by run_benchmarks.py --output json)."
    )
    parser.add_argument(
        "results_file",
        help="Path to JSON results file",
    )
    parser.add_argument(
        "--top",
        type=int,
        default=15,
        help="Number of slowest tests to display (default: 15)",
    )
    args = parser.parse_args()

    summarize(Path(args.results_file), top_n=args.top)


if __name__ == "__main__":
    main()
